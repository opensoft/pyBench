#!/usr/bin/env bash

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BENCH_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
MOUNT_DIR="${1:-$BENCH_DIR/.devcontainer/.openbenches-mounts}"
OUT_FILE="$MOUNT_DIR/docker-compose.yml"

[[ -n "${HOME:-}" ]] || {
    echo "HOME must be set to resolve openBenches mounts" >&2
    exit 1
}

command -v flock >/dev/null 2>&1 || {
    echo "flock is required to prepare openBenches mounts" >&2
    exit 1
}

normalize_root() {
    local value="$1"
    while [[ "$value" != "/" && "$value" == */ ]]; do
        value="${value%/}"
    done
    printf '%s\n' "$value"
}

resolve_root() {
    local label="$1"
    local legacy_root="$2"
    local open_root="$3"
    local new_name="OPENBENCHES_${label}_ROOT"
    local old_name="WORKBENCHES_${label}_ROOT"
    local new_value="${!new_name:-}"
    local old_value="${!old_name:-}"
    local explicit_name=""
    local selected

    if [[ -n "$new_value" && "$new_value" != /* ]]; then
        echo "$new_name must be an absolute path" >&2
        return 1
    fi
    if [[ -n "$old_value" && "$old_value" != /* ]]; then
        echo "$old_name must be an absolute path" >&2
        return 1
    fi
    if [[ -n "$new_value" ]]; then
        new_value="$(normalize_root "$new_value")"
    fi
    if [[ -n "$old_value" ]]; then
        old_value="$(normalize_root "$old_value")"
    fi

    if [[ -n "$new_value" && -n "$old_value" ]]; then
        if [[ "$new_value" != "$old_value" ]]; then
            echo "$new_name and $old_name conflict; set only one or use the same path" >&2
            return 1
        fi
        selected="$new_value"
        explicit_name="$new_name"
    elif [[ -n "$new_value" ]]; then
        selected="$new_value"
        explicit_name="$new_name"
    elif [[ -n "$old_value" ]]; then
        selected="$old_value"
        explicit_name="$old_name"
    elif [[ -d "$open_root" ]]; then
        selected="$open_root"
    elif [[ -d "$legacy_root" ]]; then
        selected="$legacy_root"
    else
        selected="$legacy_root"
    fi

    if [[ -n "$explicit_name" && ! -d "$selected" ]]; then
        echo "$explicit_name must reference an existing directory: $selected" >&2
        return 1
    fi

    printf '%s\n' "$selected"
}

config_root="$(resolve_root CONFIG "$HOME/.config/workbenches" "$HOME/.config/openbenches")"
lib_root="$(resolve_root LIB "$HOME/.local/lib/workbenches" "$HOME/.local/lib/openbenches")"
state_root="$(resolve_root STATE "$HOME/.local/state/workbenches" "$HOME/.local/state/openbenches")"

mkdir -p "$MOUNT_DIR"
exec 9>"$MOUNT_DIR/.lock"
flock 9

ensure_default_root() {
    local label="$1"
    local selected="$2"
    local new_name="OPENBENCHES_${label}_ROOT"
    local old_name="WORKBENCHES_${label}_ROOT"

    if [[ -z "${!new_name:-}" && -z "${!old_name:-}" ]]; then
        mkdir -p -- "$selected"
    fi
}

ensure_default_root CONFIG "$config_root"
ensure_default_root LIB "$lib_root"
ensure_default_root STATE "$state_root"

yaml_quote() {
    local value="$1"
    value="${value//"'"/"''"}"
    printf "'%s'" "$value"
}

tmp_file="$(mktemp "$MOUNT_DIR/.docker-compose.yml.XXXXXXXX")"
trap 'rm -f -- "$tmp_file"' EXIT

{
    printf '%s\n' \
        '# Generated by scripts/prepare-openbenches-mounts.sh.' \
        'services:' \
        '  py-bench:' \
        '    volumes:' \
        '      - type: bind'
    printf '        source: %s\n' "$(yaml_quote "$config_root")"
    printf '%s\n' \
        "        target: /home/\${USER:-brett}/.config/workbenches" \
        '        read_only: true' \
        '      - type: bind'
    printf '        source: %s\n' "$(yaml_quote "$lib_root")"
    printf '%s\n' \
        "        target: /home/\${USER:-brett}/.local/lib/workbenches" \
        '        read_only: true' \
        '      - type: bind'
    printf '        source: %s\n' "$(yaml_quote "$state_root")"
    printf '%s\n' \
        "        target: /home/\${USER:-brett}/.local/state/workbenches" \
        '        consistency: cached'
} > "$tmp_file"
chmod 0644 "$tmp_file"

if [[ -f "$OUT_FILE" && ! -L "$OUT_FILE" ]] && cmp -s "$tmp_file" "$OUT_FILE"; then
    exit 0
fi

mv -T -- "$tmp_file" "$OUT_FILE"
